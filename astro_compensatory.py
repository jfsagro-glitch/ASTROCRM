_HARD_ASPECTS = {"square", "opposition", "conjunction"}
_SOFT_ASPECTS  = {"trine", "sextile"}


def _pick_practices(planet: str, intensity: str, sign: str | None = None) -> list[str]:
    """Return practice list for a single planet at given intensity level."""
    data = SINGLE_PLANET_PRACTICES.get(planet, {})
    pracs = list(data.get("practices", {}).get(intensity, []))
    if sign:
        sign_note = data.get("in_signs", {}).get(sign)
        if sign_note:
            pracs.insert(0, sign_note)
    return pracs


def _find_pair_practices(planet_a: str, planet_b: str,
                         aspect: str, intensity: str) -> dict | None:
    """Look up aspect-pair data (both orderings of the pair)."""
    key1 = (planet_a, planet_b, aspect)
    key2 = (planet_b, planet_a, aspect)
    data = ASPECT_PAIR_PRACTICES.get(key1) or ASPECT_PAIR_PRACTICES.get(key2)
    if not data:
        return None
    result = dict(data)
    # Normalize practices to list form
    raw = data.get("practices", [])
    if isinstance(raw, dict):
        result["practices"] = raw.get(intensity, raw.get("medium", []))
    return result


def _detect_backgrounds(transit_planets: dict) -> list[dict]:
    """Detect active background narratives from slow-planet positions."""
    active = []

    saturn_sign  = transit_planets.get("saturn_sign", "")
    neptune_sign = transit_planets.get("neptune_sign", "")
    pluto_sign   = transit_planets.get("pluto_sign", "")
    uranus_lon   = transit_planets.get("uranus_lon", 0)
    jupiter_sign = transit_planets.get("jupiter_sign", "")

    if pluto_sign == "aquarius":
        active.append({"key": "pluto_aquarius", **BACKGROUND_NARRATIVES["pluto_aquarius"]})
    if neptune_sign == "aries":
        active.append({"key": "neptune_aries", **BACKGROUND_NARRATIVES["neptune_aries"]})
    if saturn_sign == "aries" and neptune_sign == "aries":
        active.append({"key": "saturn_neptune_aries",
                       **BACKGROUND_NARRATIVES["saturn_neptune_aries"]})
    if uranus_lon >= 58 and uranus_lon < 60:   # ~29° Taurus
        active.append({"key": "uranus_taurus_29",
                       **BACKGROUND_NARRATIVES["uranus_taurus_29"]})
    if jupiter_sign == "cancer":
        active.append({"key": "jupiter_cancer", **BACKGROUND_NARRATIVES["jupiter_cancer"]})

    return active


def build_compensatory_report(
    natal_chart: dict,
    transit_chart: dict,
    transit_aspects: list[dict],
    target_date: str,
    intensity: str = "medium",
    context: str | None = None,
) -> dict:
    """
    Build the full compensatory report.

    natal_chart   — output of astro_engine.calc_chart()
    transit_chart — output of astro_engine.calc_chart() for target date at noon
    transit_aspects — list of aspect dicts from calc_aspects() for transits
    intensity     — "light" | "medium" | "deep"
    context       — optional "travel|work|home|crisis|creative"
    """
    if intensity not in ("light", "medium", "deep"):
        intensity = "medium"

    # -- Natal Sun sign
    natal_planets = natal_chart.get("planets", {})
    natal_sun_lon = natal_planets.get("sun", {})
    if isinstance(natal_sun_lon, dict):
        natal_sun_lon = natal_sun_lon.get("lon", natal_sun_lon.get("longitude", 0))
    sun_sign = natal_chart.get("sun_sign") or _lon_to_sign(natal_sun_lon)

    sun_sign_data = SUN_SIGN_VOICE.get(sun_sign, {})

    # -- Transit planet positions for background detection
    tr_planets = transit_chart.get("planets", {})
    bg_input = {}
    for p in ("saturn", "neptune", "pluto", "uranus", "jupiter"):
        raw = tr_planets.get(p, {})
        lon = raw.get("lon", raw.get("longitude", 0)) if isinstance(raw, dict) else raw
        bg_input[f"{p}_lon"]  = lon
        bg_input[f"{p}_sign"] = _lon_to_sign(lon)

    backgrounds = _detect_backgrounds(bg_input)

    # -- Per-planet single practices
    active_transits = []
    for planet in ("sun", "moon", "mercury", "venus", "mars",
                   "jupiter", "saturn", "uranus", "neptune", "pluto"):
        raw = tr_planets.get(planet, {})
        if not raw:
            continue
        lon  = raw.get("lon", raw.get("longitude", 0)) if isinstance(raw, dict) else raw
        sign = _lon_to_sign(lon)
        data = SINGLE_PLANET_PRACTICES.get(planet, {})
        if not data:
            continue
        pracs = _pick_practices(planet, intensity, sign)
        active_transits.append({
            "planet":     planet,
            "sign":       sign,
            "practices":  pracs,
            "tension_signal": data.get("tension_signal", ""),
            "function":   data.get("function", ""),
        })

    # -- Aspect-pair practices (transit-to-transit only, hard aspects first)
    aspect_pairs_out = []
    seen_pairs: set = set()
    for asp in transit_aspects:
        # Support both naming conventions:
        # - "planet1"/"planet2" from calc_aspects() transit-to-transit
        # - "transit_planet"/"natal_planet" from transits() natal aspects
        p1  = (asp.get("transit_planet") or asp.get("transiting_planet")
               or asp.get("planet1") or asp.get("p1", ""))
        p2  = (asp.get("natal_planet") or asp.get("planet2") or asp.get("p2", ""))
        kind = asp.get("aspect", "")
        key = tuple(sorted([p1, p2]) + [kind])
        if key in seen_pairs:
            continue
        seen_pairs.add(key)
        pair_data = _find_pair_practices(p1, p2, kind, intensity)
        if pair_data:
            aspect_pairs_out.append({
                "pair":      f"{p1}_{p2}_{kind}",
                "name":      pair_data.get("name", ""),
                "image":     pair_data.get("image", ""),
                "tension":   pair_data.get("tension", ""),
                "context":   pair_data.get("context", ""),
                "practices": pair_data.get("practices", []),
            })

    # -- Opening phrase
    bg_key = backgrounds[0]["key"] if backgrounds else "low_tension_background"
    opening_options = PERIOD_OPENINGS.get(bg_key, PERIOD_OPENINGS["low_tension_background"])
    opening = random.choice(opening_options)

    return {
        "target_date":    target_date,
        "intensity":      intensity,
        "context":        context,
        "opening":        opening,
        "background": {
            "active":     backgrounds,
        },
        "sun_sign_note":  {
            "sign":       sun_sign,
            **sun_sign_data
        },
        "active_transits":   active_transits,
        "aspect_pairs":      aspect_pairs_out,
    }


def _lon_to_sign(lon: float) -> str:
    signs = ["aries","taurus","gemini","cancer","leo","virgo",
             "libra","scorpio","sagittarius","capricorn","aquarius","pisces"]
    return signs[int(lon % 360 / 30)]
