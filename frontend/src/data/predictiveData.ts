export function generatePersonalDailyScores(
  startStr: string,
  endStr: string,
): PersonalDailyScore[] {
  const MOON_REF_DATE     = new Date(2025, 0, 29);
  const MOON_REF_LON      = 310.5;
  const MOON_DAILY_MOTION = 13.176;
  const SYNODIC_MONTH     = 29.530589;
  const SIGN_NAMES_EN = [
    'aries','taurus','gemini','cancer','leo','virgo',
    'libra','scorpio','sagittarius','capricorn','aquarius','pisces',
  ];

  const start = new Date(startStr);
  const end   = new Date(endStr);

  // Index events by date (including range events)
  const eventsByDate = new Map<string, string[]>();
  for (const e of PLANETARY_EVENTS) {
    const eS = new Date(e.date);
    const eE = e.end ? new Date(e.end) : new Date(e.date);
    const overlapStart = new Date(Math.max(eS.getTime(), start.getTime()));
    const overlapEnd   = new Date(Math.min(eE.getTime(), end.getTime()));
    for (let d = new Date(overlapStart); d <= overlapEnd; d.setDate(d.getDate() + 1)) {
      const ds = d.toISOString().slice(0, 10);
      const arr = eventsByDate.get(ds) ?? [];
      if (!arr.includes(e.title)) arr.push(e.title);
      eventsByDate.set(ds, arr);
    }
  }

  const days: PersonalDailyScore[] = [];

  for (let cur = new Date(start); cur <= end; cur.setDate(cur.getDate() + 1)) {
    const dateStr   = cur.toISOString().slice(0, 10);
    const daysSince = (cur.getTime() - MOON_REF_DATE.getTime()) / 86_400_000;
    const moonLon   = ((MOON_REF_LON + daysSince * MOON_DAILY_MOTION) % 360 + 360) % 360;
    const moonSign  = SIGN_NAMES_EN[Math.floor(moonLon / 30)];
    const phaseDay  = ((daysSince % SYNODIC_MONTH) + SYNODIC_MONTH) % SYNODIC_MONTH;

    const scores: Record<string, number> = {};
    for (const s of PERSONAL_SPHERES) scores[s.id] = 50;

    // Moon sign
    const msBonus = PERSONAL_MOON_BONUS[moonSign] ?? {};
    for (const [k, v] of Object.entries(msBonus)) if (k in scores && v != null) scores[k] += v;

    // Day of week
    const dowBonus = PERSONAL_DOW_BONUS[cur.getDay()] ?? {};
    for (const [k, v] of Object.entries(dowBonus)) if (k in scores && v != null) scores[k] += v;

    // Moon phase
    const phaseBonus = personalPhaseBonus(phaseDay);
    for (const [k, v] of Object.entries(phaseBonus)) if (k in scores && v != null) scores[k] += v;

    // Planetary events
    const dayEvents = eventsByDate.get(dateStr) ?? [];
    for (const evt of dayEvents) {
      const bonus = personalEventBonus(evt);
      for (const [k, v] of Object.entries(bonus)) if (k in scores && v != null) scores[k] += v;
    }

    // Clamp 5–98
    for (const k of Object.keys(scores)) scores[k] = Math.max(5, Math.min(98, scores[k]));

    const topSpheres = Object.entries(scores)
      .sort(([, a], [, b]) => b - a).slice(0, 3).map(([k]) => k);

    days.push({
      date: dateStr,
      moonSign,
      moonPhaseDay: phaseDay,
      moonPhaseLabel: personalMoonPhaseLabel(phaseDay),
      moonPhaseIcon:  personalMoonPhaseIcon(phaseDay),
      sphereScores: { ...scores },
      topSpheres,
      events: dayEvents,
    });
  }

  return days;
}
