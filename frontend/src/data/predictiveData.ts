function aspectCategory(aspect: string): 'conj' | 'harm' | 'tense' {
  if (aspect === 'conjunction') return 'conj';
  if (['trine', 'sextile'].includes(aspect)) return 'harm';
  if (['opposition', 'square'].includes(aspect)) return 'tense';
  return 'harm'; // minor aspects default to harmonic
}

export function getTransitInterp(
  transitPlanet: string,
  aspect: string,
  natalPlanet: string,
): AspectInterp | null {
  const cat = aspectCategory(aspect);
  const key = `${transitPlanet}_${cat}_${natalPlanet}`;
  return TRANSIT_INTERPS[key] ?? null;
}

export function getPlanetRuName(p: string): string {
  const N: Record<string, string> = {
    sun:'Солнце', moon:'Луна', mercury:'Меркурий', venus:'Венера', mars:'Марс',
    jupiter:'Юпитер', saturn:'Сатурн', uranus:'Уран', neptune:'Нептун', pluto:'Плутон',
    node:'Узел', chiron:'Хирон', lilith:'Лилит',
  };
  return N[p] ?? p;
}

export function getAspectRuName(a: string): string {
  const N: Record<string, string> = {
    conjunction:'Соединение', opposition:'Оппозиция', trine:'Трин', square:'Квадратура',
    sextile:'Секстиль', quincunx:'Квинконс', semisextile:'Полусекстиль',
    semisquare:'Полуквадрат', sesquiquadrate:'Полутора-квадрат',
    quintile:'Квинтиль', biquintile:'Биквинтиль',
    parallel:'Параллель', contra_parallel:'Контрпараллель',
  };
  return N[a] ?? a;
}

export function aspectEnergyColor(aspect: string, isDark: boolean): string {
  const cat = aspectCategory(aspect);
  if (cat === 'conj') return isDark ? 'text-yellow-300' : 'text-yellow-600';
  if (cat === 'harm') return isDark ? 'text-green-400' : 'text-green-600';
  return isDark ? 'text-red-400' : 'text-red-600';
}

// Generate a period overview text based on technique type
export function getPeriodTheme(
  technique: string,
  result: Record<string, unknown>,
): { headline: string; points: string[] } {
  if (technique === 'profections') {
    const house = result.annual_house as number;
    const info = PROFECTION_HOUSE_MEANINGS[house];
    if (info) return {
      headline: `${info.symbol} ${info.theme}`,
      points: [info.advice, `Ключевые сферы: ${info.areas.join(', ')}`, `Лорд года: ${getPlanetRuName(result.annual_lord as string)} — следите за всеми его транзитами этот год.`],
    };
  }
  if (technique === 'transits') {
    const aspects = (result.aspects as Array<Record<string, unknown>>) ?? [];
    const outer = aspects.filter(a => ['saturn','uranus','neptune','pluto','jupiter'].includes(a.transit_planet as string));
    const tense = outer.filter(a => ['opposition','square'].includes(a.aspect as string));
    const harm = outer.filter(a => ['conjunction','trine','sextile'].includes(a.aspect as string));
    const hasSaturn = outer.some(a => a.transit_planet === 'saturn');
    const hasJupiter = outer.some(a => a.transit_planet === 'jupiter');
    const hasPluto = outer.some(a => a.transit_planet === 'pluto');
    const hasUranus = outer.some(a => a.transit_planet === 'uranus');
    const hasNeptune = outer.some(a => a.transit_planet === 'neptune');

    let headline = '';
    const points: string[] = [];

    if (outer.length === 0) {
      headline = 'Спокойный период — внешние планеты не создают значимых аспектов';
      points.push('Сосредоточьтесь на повседневных задачах и личных планетах (Марс, Венера, Меркурий).');
      points.push('Хорошее время для завершения начатого, а не для старта кардинальных изменений.');
    } else if (tense.length >= 3) {
      headline = `Напряжённый период: ${tense.length} сложных транзита внешних планет`;
      points.push('Несколько внешних планет создают напряжение — это время испытания на прочность, но и роста.');
      points.push('Не принимайте необратимых решений в пиковые моменты орбов. Терпение — главный ресурс.');
    } else if (harm.length >= 2 && tense.length === 0) {
      headline = `Благоприятный период: ${harm.length} поддерживающих транзита внешних планет`;
      points.push('Внешние планеты создают гармоничный фон — хорошее время для запуска важных дел.');
      points.push('Возможности могут появляться неожиданно. Открывайтесь тому, что приходит.');
    } else {
      headline = `Смешанный период: ${outer.length} транзитов внешних планет (${harm.length} поддерж., ${tense.length} напряж.)`;
      points.push('Чередуйте активные шаги с периодами осмысления — не всё идёт по плану, и это нормально.');
    }

    if (hasJupiter) points.push('Юпитер активен — ищите возможности для роста и расширения.');
    if (hasSaturn) points.push('Сатурн активен — дисциплина и ответственность дают результат. Не уклоняйтесь от трудного.');
    if (hasUranus) points.push('Уран активен — готовьтесь к неожиданным поворотам и переменам.');
    if (hasNeptune) points.push('Нептун активен — интуиция работает, но берегитесь самообмана.');
    if (hasPluto) points.push('Плутон активен — глубинная трансформация неизбежна. Принимайте, не сопротивляйтесь.');

    return { headline, points };
  }
  if (technique === 'secondary_progressions' || technique === 'secondary') {
    const progPlanets = result.prog_planets as Record<string, { sign: string; deg_min: string }> ?? {};
    const progSun = progPlanets.sun;
    const progMoon = progPlanets.moon;
    const points: string[] = [];
    if (progSun) {
      const interp = PROG_SUN_SIGN_INTERP[progSun.sign];
      points.push(interp ?? `Прогр. Солнце в ${progSun.sign} ${progSun.deg_min}`);
    }
    if (progMoon) {
      points.push(`Прогр. Луна в ${progMoon.sign} ${progMoon.deg_min} — смотрите блок интерпретации Луны ниже.`);
    }
    return {
      headline: 'Вторичные прогрессии: внутреннее созревание',
      points,
    };
  }
  if (technique === 'solar_arc' || technique === 'solar-arc') {
    const aspects = (result.aspects_directed_to_natal as Array<Record<string, unknown>>) ?? [];
    const exact = aspects.filter(a => (a.orb as number) < 1.0);
    const points: string[] = [];
    if (exact.length > 0) {
      points.push(`${exact.length} точных аспектов (орб < 1°) — это конкретные события или переходы этого года.`);
      exact.slice(0, 2).forEach(a => {
        const dp = a.directed_planet as string;
        const interp = SOLAR_ARC_PLANET_INTERP[dp];
        if (interp) points.push(`${getPlanetRuName(dp)} (направленный): ${interp.text}`);
      });
    } else {
      points.push('Нет точных аспектов (орб < 1°) — событийно спокойный период. Работайте с тем, что уже началось.');
    }
    const arcDeg = result.solar_arc_deg as number;
    if (arcDeg) points.push(`Дуга ${arcDeg.toFixed(1)}° ≈ ${arcDeg.toFixed(0)} лет жизни — все точки карты продвинулись на этот угол.`);
    return { headline: 'Солярная дуга: хронологический маркер жизни', points };
  }
  if (technique === 'tertiary_progressions' || technique === 'tertiary') {
    const aspects = (result.aspects_prog_to_natal as Array<Record<string, unknown>>) ?? [];
    return {
      headline: 'Третичные прогрессии: эмоциональный ритм',
      points: [
        'Третичные прогрессии быстрее вторичных в 13 раз — они отражают психоэмоциональные циклы.',
        aspects.length > 0 ? `${aspects.length} активных аспектов. Сравните с вторичными — совпадения усиливают вероятность события.` : 'Аспектов нет — тихий внутренний период.',
      ],
    };
  }
  if (technique === 'converse_progressions' || technique === 'converse') {
    const aspects = (result.aspects_prog_to_natal as Array<Record<string, unknown>>) ?? [];
    return {
      headline: 'Конверсионные прогрессии: кармический слой',
      points: [
        'Прогрессии назад от рождения — показывают глубинные психологические паттерны и кармические темы.',
        aspects.length > 0 ? `${aspects.length} аспектов. Совпадение с прямыми прогрессиями — сильный сигнал.` : 'Активных аспектов нет — внешне спокойный, но внутренне важный период.',
      ],
    };
  }
  return { headline: 'Результат вычислен', points: [] };
}

