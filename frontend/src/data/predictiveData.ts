function aspectCategory(aspect: string): 'conj' | 'harm' | 'tense' {
  if (aspect === 'conjunction') return 'conj';
  if (['trine', 'sextile'].includes(aspect)) return 'harm';
  if (['opposition', 'square'].includes(aspect)) return 'tense';
  return 'harm'; // minor aspects default to harmonic
}

export function getTransitInterp(
  transitPlanet: string,
  aspect: string,
  natalPlanet: string,
): AspectInterp | null {
  const cat = aspectCategory(aspect);
  const key = `${transitPlanet}_${cat}_${natalPlanet}`;
  return TRANSIT_INTERPS[key] ?? null;
}

export function getPlanetRuName(p: string): string {
  const N: Record<string, string> = {
    sun:'Солнце', moon:'Луна', mercury:'Меркурий', venus:'Венера', mars:'Марс',
    jupiter:'Юпитер', saturn:'Сатурн', uranus:'Уран', neptune:'Нептун', pluto:'Плутон',
    node:'Узел', chiron:'Хирон', lilith:'Лилит',
  };
  return N[p] ?? p;
}

export function getAspectRuName(a: string): string {
  const N: Record<string, string> = {
    conjunction:'Соединение', opposition:'Оппозиция', trine:'Трин', square:'Квадратура',
    sextile:'Секстиль', quincunx:'Квинконс', semisextile:'Полусекстиль',
    semisquare:'Полуквадрат', sesquiquadrate:'Полутора-квадрат',
    quintile:'Квинтиль', biquintile:'Биквинтиль',
    parallel:'Параллель', contra_parallel:'Контрпараллель',
  };
  return N[a] ?? a;
}

export function aspectEnergyColor(aspect: string, isDark: boolean): string {
  const cat = aspectCategory(aspect);
  if (cat === 'conj') return isDark ? 'text-yellow-300' : 'text-yellow-600';
  if (cat === 'harm') return isDark ? 'text-green-400' : 'text-green-600';
  return isDark ? 'text-red-400' : 'text-red-600';
}

// Generate a period overview text based on technique type
export function getPeriodTheme(
  technique: string,
  result: Record<string, unknown>,
): { headline: string; points: string[] } {
  if (technique === 'profections') {
    const house = result.annual_house as number;
    const info = PROFECTION_HOUSE_MEANINGS[house];
    if (info) return {
      headline: `Год активации ${info.title} (Дом ${house})`,
      points: [info.advice, `Ключевые сферы: ${info.areas.join(', ')}`, `Лорд года: ${getPlanetRuName(result.annual_lord as string)}`],
    };
  }
  if (technique === 'transits') {
    const aspects = (result.aspects as Array<Record<string, unknown>>) ?? [];
    const outer = aspects.filter(a => ['saturn','uranus','neptune','pluto','jupiter'].includes(a.transit_planet as string));
    const summary = outer.slice(0, 3).map(a =>
      `${getPlanetRuName(a.transit_planet as string)} ${getAspectRuName(a.aspect as string)} ${getPlanetRuName(a.natal_planet as string)}`
    );
    return {
      headline: `Активных транзитов: ${aspects.length} (ключевых внешних планет: ${outer.length})`,
      points: summary.length ? summary : ['Нет значимых транзитов внешних планет'],
    };
  }
  if (technique === 'secondary_progressions') {
    const progPlanets = result.prog_planets as Record<string, { sign: string; deg_min: string }> ?? {};
    const progSun = progPlanets.sun;
    const progMoon = progPlanets.moon;
    return {
      headline: 'Прогрессированные позиции',
      points: [
        progSun ? `☉ Прогр. Солнце в ${progSun.sign} ${progSun.deg_min}` : '',
        progMoon ? `☽ Прогр. Луна в ${progMoon.sign} ${progMoon.deg_min}` : '',
      ].filter(Boolean),
    };
  }
  return { headline: 'Результат вычислен', points: [] };
}

