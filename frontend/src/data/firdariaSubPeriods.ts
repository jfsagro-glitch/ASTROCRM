export function getFirdariaSubInterpretation(
  major: string | null | undefined,
  sub: string | null | undefined,
): FirdariaSubInterpretation | null {
  if (!major || !sub) return null;
  const m = major as FirdariaPlanet;
  const s = sub as FirdariaPlanet;
  if (!MAJOR_THEME[m] || !SUB_MODE[s]) return null;
  const key = `${m}-${s}`;
  return {
    tone:         PAIR_TONE[key]     ?? `${m} → ${s}`,
    major_theme:  MAJOR_THEME[m],
    sub_mode:     SUB_MODE[s],
    practice:     PAIR_PRACTICE[key] ?? 'Действуйте в духе обоих светил периода.',
  };
}
