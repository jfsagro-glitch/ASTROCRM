export interface SphereScore {
  sphere: SphereDefinition;
  score: number;          // 0–100
  topAspects: Array<{ aspect: AspectData; interp: PairInterp | null; category: 'conj'|'harm'|'tense' }>;
}

export function getAspectCategory(aspect: string): 'conj' | 'harm' | 'tense' | null {
  if (aspect === 'conjunction') return 'conj';
  if (['trine', 'sextile'].includes(aspect)) return 'harm';
  if (['square', 'opposition', 'quincunx', 'semisquare', 'sesquisquare'].includes(aspect)) return 'tense';
  return null;
}

export function getPairInterp(p1: string, p2: string): PairInterp | null {
  return PAIR_INTERPS[pairKey(p1, p2)] ?? null;
}

export function scoreSpheres(aspects: AspectData[]): SphereScore[] {
  return LIFE_SPHERES.map(sphere => {
    let score = 50;
    const scored: Array<{ aspect: AspectData; interp: PairInterp | null; category: 'conj'|'harm'|'tense'; delta: number }> = [];

    for (const pair of sphere.pairs) {
      const rel = aspects.filter(a =>
        (a.p1 === pair.p1 && a.p2 === pair.p2) ||
        (a.p1 === pair.p2 && a.p2 === pair.p1)
      );
      for (const asp of rel) {
        const cat = getAspectCategory(asp.aspect);
        if (!cat) continue;
        const delta = cat === 'harm' ? pair.harmScore
                    : cat === 'conj' ? pair.conjScore
                    : pair.tenseScore;
        score += delta;
        scored.push({ aspect: asp, interp: getPairInterp(asp.p1, asp.p2), category: cat, delta });
      }
    }

    // Sort by absolute contribution, pick top 5
    scored.sort((a, b) => Math.abs(b.delta) - Math.abs(a.delta));
    const topAspects = scored.slice(0, 5).map(s => ({ aspect: s.aspect, interp: s.interp, category: s.category }));

    return {
      sphere,
      score: Math.max(0, Math.min(100, score)),
      topAspects,
    };
  });
}

export function getAspectInterpText(interp: PairInterp, cat: 'conj'|'harm'|'tense'): string {
  return cat === 'conj' ? interp.conj : cat === 'harm' ? interp.harm : interp.tense;
}

export function getSphereInterpretation(ss: SphereScore): string {
  if (ss.score < 45) return ss.sphere.interpretLow;
  if (ss.score < 72) return ss.sphere.interpretMid;
  return ss.sphere.interpretHigh;
}

export function getSphereActions(ss: SphereScore): string[] {
  if (ss.score < 45) return ss.sphere.lowActions;
  if (ss.score < 72) return ss.sphere.midActions;
  return ss.sphere.highActions;
}

