  const conf = ENERGY_CONFIG[period.energy] ?? ENERGY_CONFIG['переменный'];
  const moonInterp = MOON_SIGN_INTERP[period.moon_sign];
  const scores = computeSphereScores(period.key_aspects, period.energy);
